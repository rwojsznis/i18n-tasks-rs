pub fn language_name(locale: &str) -> String {
    let code = locale.to_uppercase();
    NAMES
        .iter()
        .find(|(c, _)| *c == code)
        .map_or_else(|| locale.to_string(), |(_, name)| (*name).to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_two_letter_code_is_named_and_anything_else_is_kept() {
        assert_eq!(language_name("de"), "German");
        assert_eq!(language_name("nb"), "Bokmål, Norwegian");
        assert_eq!(language_name("fil"), "fil");
        assert_eq!(language_name("pt-BR"), "pt-BR");
    }
}
